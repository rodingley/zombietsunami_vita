#!/usr/bin/env python3
"""Generates src/jni_gen.inc: JNIEnv function indexes, names and default logging stubs."""
import sys
names = ["reserved0","reserved1","reserved2","reserved3","GetVersion","DefineClass","FindClass",
"FromReflectedMethod","FromReflectedField","ToReflectedMethod","GetSuperclass","IsAssignableFrom",
"ToReflectedField","Throw","ThrowNew","ExceptionOccurred","ExceptionDescribe","ExceptionClear",
"FatalError","PushLocalFrame","PopLocalFrame","NewGlobalRef","DeleteGlobalRef","DeleteLocalRef",
"IsSameObject","NewLocalRef","EnsureLocalCapacity","AllocObject","NewObject","NewObjectV","NewObjectA",
"GetObjectClass","IsInstanceOf","GetMethodID"]
types = ["Object","Boolean","Byte","Char","Short","Int","Long","Float","Double","Void"]
for t in types: names += [f"Call{t}Method", f"Call{t}MethodV", f"Call{t}MethodA"]
for t in types: names += [f"CallNonvirtual{t}Method", f"CallNonvirtual{t}MethodV", f"CallNonvirtual{t}MethodA"]
names.append("GetFieldID")
ft = ["Object","Boolean","Byte","Char","Short","Int","Long","Float","Double"]
for t in ft: names.append(f"Get{t}Field")
for t in ft: names.append(f"Set{t}Field")
names.append("GetStaticMethodID")
for t in types: names += [f"CallStatic{t}Method", f"CallStatic{t}MethodV", f"CallStatic{t}MethodA"]
names.append("GetStaticFieldID")
for t in ft: names.append(f"GetStatic{t}Field")
for t in ft: names.append(f"SetStatic{t}Field")
names += ["NewString","GetStringLength","GetStringChars","ReleaseStringChars","NewStringUTF",
"GetStringUTFLength","GetStringUTFChars","ReleaseStringUTFChars","GetArrayLength","NewObjectArray",
"GetObjectArrayElement","SetObjectArrayElement"]
pt = ["Boolean","Byte","Char","Short","Int","Long","Float","Double"]
for t in pt: names.append(f"New{t}Array")
for t in pt: names.append(f"Get{t}ArrayElements")
for t in pt: names.append(f"Release{t}ArrayElements")
for t in pt: names.append(f"Get{t}ArrayRegion")
for t in pt: names.append(f"Set{t}ArrayRegion")
names += ["RegisterNatives","UnregisterNatives","MonitorEnter","MonitorExit","GetJavaVM",
"GetStringRegion","GetStringUTFRegion","GetPrimitiveArrayCritical","ReleasePrimitiveArrayCritical",
"GetStringCritical","ReleaseStringCritical","NewWeakGlobalRef","DeleteWeakGlobalRef","ExceptionCheck",
"NewDirectByteBuffer","GetDirectBufferAddress","GetDirectBufferCapacity","GetObjectRefType"]
assert len(names) == 233, len(names)
# sanity checks against indexes seen in the game's machine code
assert names.index("FindClass")==6 and names.index("NewGlobalRef")==21
assert names.index("GetObjectClass")==31 and names.index("GetMethodID")==33
assert names.index("CallObjectMethodV")==35 and names.index("NewStringUTF")==167
assert names.index("GetStringUTFChars")==169
out = ["/* GENERATED by tools/gen_jni.py -- do not edit */",
       f"#define JNI_NUM_FUNCS {len(names)}", "enum {"]
for i,n in enumerate(names): out.append(f"  JI_{n} = {i},")
out.append("};")
out.append("static const char *const jni_names[JNI_NUM_FUNCS] = {")
for n in names: out.append(f'  "{n}",')
out.append("};")
for i in range(len(names)):
    out.append(f"static intptr_t jstub_{i}(void) {{ return jni_unimpl({i}); }}")
out.append("static void *const jni_stub_table[JNI_NUM_FUNCS] = {")
for i in range(len(names)): out.append(f"  (void *)jstub_{i},")
out.append("};")
open(sys.argv[1],"w").write("\n".join(out)+"\n")
