#!/bin/bash
# Generates direct_imports.c: the table entries for every symbol the game
# needs that we do NOT replace by hand in imports.c.
#   - OpenGL (gl*)  -> do-nothing stub for now (stage 2a)
#   - zlib          -> the copy of zlib bundled in src/zlib
#   - everything the Vita SDK's C / math / pthread libraries really define
#     -> the SDK function itself
#   - anything else -> left out (the loader logs it as MISSING)
#
# usage: gen_direct.sh needed_symbols.txt imports.c [more .c files with S("name",..) tables] out.c
# env:   NM (default arm-vita-eabi-nm), SDKLIBS (default: libc.a libm.a libpthread.a
#        from $VITASDK/arm-vita-eabi/lib)
set -e
export LC_ALL=C
NEEDED="$1"; shift; OUT="${@: -1}"; set -- "${@:1:$(($#-1))}"; IMPORTS="$*"
NM="${NM:-arm-vita-eabi-nm}"
if [ -z "$SDKLIBS" ]; then
  L="$VITASDK/arm-vita-eabi/lib"
  SDKLIBS="$L/libc.a $L/libm.a $L/libpthread.a"
fi

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

# names we implement by hand in imports.c
grep -ho 'S("[^"]*"' $IMPORTS | sed 's/S("//; s/"$//' | sort -u > "$TMP/shim"

# symbols the SDK libraries define
for f in $SDKLIBS; do
  [ -f "$f" ] && "$NM" -g --defined-only -P "$f" 2>/dev/null | awk 'NF>=2 && $2 ~ /^[TDBRWVuvi]$/ {print $1}'
done | sort -u > "$TMP/sdk"

# bundled zlib
cat > "$TMP/zlib" <<'EOF'
adler32
crc32
deflate
deflateEnd
deflateInit2_
deflateReset
get_crc_table
inflate
inflateEnd
inflateInit2_
inflateInit_
inflateReset
EOF

sort -u "$NEEDED" > "$TMP/need"
comm -23 "$TMP/need" "$TMP/shim" > "$TMP/rest"
grep '^gl' "$TMP/rest" > "$TMP/gl" || true
grep -v '^gl' "$TMP/rest" > "$TMP/nongl" || true
comm -12 "$TMP/nongl" "$TMP/zlib" > "$TMP/zl"
comm -23 "$TMP/nongl" "$TMP/zlib" > "$TMP/nonz"
comm -12 "$TMP/nonz" "$TMP/sdk" > "$TMP/direct"
comm -23 "$TMP/nonz" "$TMP/sdk" > "$TMP/absent"

# real OpenGL (vitaGL): link the gl* functions straight to the library
if [ -n "$REAL_GL" ]; then
  cat "$TMP/gl" >> "$TMP/direct"
  sort -u -o "$TMP/direct" "$TMP/direct"
  : > "$TMP/gl"
fi

{
  echo "/* GENERATED by tools/gen_direct.sh -- do not edit */"
  echo '#include <stdint.h>'
  echo '#include "so_util.h"'
  echo 'extern int gl_stub(void);'
  i=0
  while read -r n; do
    echo "extern void d_$i(void) __asm__(\"$n\");"
    i=$((i+1))
  done < <(cat "$TMP/zl" "$TMP/direct")
  echo 'const so_default_dynlib direct_dynlib[] = {'
  i=0
  while read -r n; do
    echo "  { \"$n\", (uintptr_t)&d_$i },"
    i=$((i+1))
  done < <(cat "$TMP/zl" "$TMP/direct")
  while read -r n; do
    echo "  { \"$n\", (uintptr_t)gl_stub },"
  done < "$TMP/gl"
  echo '};'
  echo 'const int direct_dynlib_count = sizeof(direct_dynlib) / sizeof(direct_dynlib[0]);'
  echo '/* not provided by anything (the loader will report these as MISSING):'
  sed 's/^/ *   /' "$TMP/absent"
  echo ' */'
} > "$OUT"

echo "gen_direct: $(wc -l < "$TMP/shim") by hand, $(wc -l < "$TMP/direct") from SDK, $(wc -l < "$TMP/zl") zlib, $(wc -l < "$TMP/gl") GL stubs, $(wc -l < "$TMP/absent") absent"
